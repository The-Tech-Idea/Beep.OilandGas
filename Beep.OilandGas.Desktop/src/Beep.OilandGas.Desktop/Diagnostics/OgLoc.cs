    public static IReadOnlyList<OgCultureOption> SupportedCultures { get; } =
    [
        new OgCultureOption(English, "English", RightToLeft: false),
        new OgCultureOption(Arabic, "العربية", RightToLeft: true),
    ];

    private string _cultureName = English;

    public event EventHandler? LanguageChanged;

    public string CultureName => _cultureName;

    public bool IsRightToLeft => string.Equals(_cultureName, Arabic, StringComparison.OrdinalIgnoreCase);

    public IReadOnlyList<OgCultureOption> Cultures => SupportedCultures;

    public void SetCulture(string cultureName)
    {
        if (string.IsNullOrWhiteSpace(cultureName)
            || string.Equals(cultureName, _cultureName, StringComparison.OrdinalIgnoreCase))
        {
            return;
        }

        var known = SupportedCultures.Any(option =>
            string.Equals(option.Name, cultureName, StringComparison.OrdinalIgnoreCase));

        if (!known)
        {
            return;
        }

        _cultureName = cultureName;
        LanguageChanged?.Invoke(this, EventArgs.Empty);
    }

    public string Get(string key, params object?[] args)
    {
        if (string.IsNullOrWhiteSpace(key))
        {
            return string.Empty;
        }

        var template =
            Find(ActiveStrings(), key)
            ?? Find(EnglishStrings, key)
            ?? key;

        return args is { Length: > 0 } ? string.Format(template, args) : template;
    }

    private IReadOnlyDictionary<string, string> ActiveStrings() =>
        IsRightToLeft ? ArabicStrings : EnglishStrings;

    private static string? Find(IReadOnlyDictionary<string, string> source, string key) =>
        source.TryGetValue(key, out var value) ? value : null;
